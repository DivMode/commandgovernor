import * as C from "./common.mjs";
const RUN = Date.now().toString(36);
const out = C.evidence("s1-02-supervisor-replacement");
const c = await C.newClient("cg-sup-1", out);
const P0 = c.hello.supervisorPid, G0 = c.hello.supervisorGeneration; out("supervisor before", { pid: P0, generation: G0 });
let roots = await C.list(c);
if (!roots.length) { await C.createRoot(c, { name: `cg-s1-02-${RUN}` }); roots = await C.list(c); }
const before = roots.map((r) => ({ id: C.sid(r), pid: r.workerPid, state: r.workerState })).sort((a, b) => a.id.localeCompare(b.id));
out("roots before", before);
const descBefore = C.workerDescriptors().length; out("worker descriptors before", descBefore);
out("ps before", C.psTree());
out("SIGKILL supervisor", P0, C.kill(P0, "SIGKILL"));
const t0 = Date.now();
await C.waitUntil(() => !C.pidAlive(P0), 10000);
const c2 = await C.connectEventually(C.SOCK, { clientId: "cg-sup-2", log: out.wire }, 60000);
const took = Date.now() - t0;
out("replacement supervisor", { pid: c2.hello.supervisorPid, generation: c2.hello.supervisorGeneration, tookMs: took });
out.check("a replacement supervisor came up without any client starting it", c2.hello.supervisorPid !== P0 && c2.hello.supervisorGeneration !== G0);
const after = (await C.list(c2)).map((r) => ({ id: C.sid(r), pid: r.workerPid, state: r.workerState })).sort((a, b) => a.id.localeCompare(b.id));
out("roots after", after);
out.check("every root adopted under the same active-session id with the same worker pid", JSON.stringify(before.map(({ id, pid }) => ({ id, pid }))) === JSON.stringify(after.map(({ id, pid }) => ({ id, pid }))));
out.check("no duplicate root workers", after.length === before.length && C.workerDescriptors().length === descBefore, { descriptors: C.workerDescriptors().length });
const tree = C.psTree(); const listeners = C.socketListeners(C.SOCK);
out("ps after (orphaned workers are reparented to pid 1 by the OS; the replacement is spawned by a worker)", tree); out("processes listening on daemon.sock", listeners);
out.check("exactly one process listens on the public daemon socket", listeners.length === 1 && listeners[0] === c2.hello.supervisorPid, { listeners, hello: c2.hello.supervisorPid });
const id = after[0].id; await C.attach(c2, id);
const p = await C.prompt(c2, id, "ECHO:after-supervisor-replacement"); await C.waitForIdle(c2, id);
const m = await C.getMessages(c2, id); const last = JSON.stringify((m.data.messages ?? m.data).at(-1)?.content ?? "");
out.check("adopted worker still serves prompts through the new supervisor", p.success && last.includes("after-supervisor-replacement"), last.slice(0, 80));
c2.close(); process.exit(out.failed ? 1 : 0);
