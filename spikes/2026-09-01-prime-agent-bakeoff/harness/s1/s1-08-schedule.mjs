import fs from "node:fs"; import path from "node:path";
import * as C from "./common.mjs";
const RUN = Date.now().toString(36);
const out = C.evidence("s1-08-schedule");
const c = await C.newClient("cg-sched", out);
const A = await C.createRoot(c, { name: `cg-s1-08-${RUN}` }); const id = C.sid(A); await C.attach(c, id);
const tag = `SLOW:20:500`; const isTick = (r) => r.lastUser === tag;
const before = C.mockRequests().filter(isTick).length;
const add = await c.request({ type: "cron_add", activeSessionId: id, schedule: "every 20s", prompt: tag }); out("cron_add", add.success ? add.data : add);
out.check("recurring job accepted", add.success);
const jf = `${C.AGENT_DIR}/session-artifacts/${A.sessionId}/scheduled-jobs.json`; await C.waitUntil(() => fs.existsSync(jf), 15000); out("jobs file", jf);
const jobState = () => JSON.parse(fs.readFileSync(jf, "utf8"));
out("job state after add", JSON.stringify(jobState()).slice(0, 500));
const t0 = Date.now(); await C.waitUntil(() => C.mockRequests().filter(isTick).length >= before + 1, 45000, 200);
out(`first tick delivered to the model after ${Date.now() - t0}ms`);
await C.sleep(1500); out("job state during delivery", JSON.stringify(jobState()).slice(0, 700));
out("SIGKILL worker during the scheduled turn", A.workerPid, C.kill(A.workerPid, "SIGKILL")); const killAt = Date.now();
const r = await C.recoverRoot(c, id, A.workerPid, out); const id2 = C.sid(r.summary); out("recovered", { path: r.path, id2, afterMs: Date.now() - killAt });
out("job state right after reopen", JSON.stringify(jobState()).slice(0, 700));
await C.sleep(4000);
const replayed = C.mockRequests().filter((x) => isTick(x) && Date.parse(x.ts) > killAt && Date.parse(x.ts) < killAt + 15000).length;
out.check("the interrupted tick was not re-delivered on restart (no immediate replay)", replayed === 0, { deliveredWithin15s: replayed });
const st = jobState(); const js = JSON.stringify(st);
out.check("job persisted with an advanced schedule and no dangling dispatch after recovery", /nextRunAt/.test(js) && !/"dispatches":\[\{/.test(js), js.slice(0, 300));
const future = await C.waitUntil(() => C.mockRequests().filter((x) => isTick(x) && Date.parse(x.ts) > killAt + 15000).length >= 1 ? true : null, 70000, 250).catch(() => false);
out.check("future ticks continue after recovery", future === true);
const jobs = await c.request({ type: "cron_list", activeSessionId: id2 }); out("cron_list", JSON.stringify(jobs.data).slice(0, 400));
const jobId = add.data?.job?.id ?? st.jobs?.[0]?.id; const cancel = await c.request({ type: "cron_cancel", activeSessionId: id2, jobId }); out("cron_cancel", cancel.success ? "ok" : cancel.error);
c.close(); process.exit(out.failed ? 1 : 0);
