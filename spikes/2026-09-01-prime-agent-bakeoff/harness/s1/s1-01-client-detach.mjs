import * as C from "./common.mjs";
const RUN = Date.now().toString(36);
const out = C.evidence("s1-01-client-detach");
const c1 = await C.newClient("cg-detach-1", out);
const s = await C.createRoot(c1, { name: `cg-s1-01-${RUN}` }); const id = C.sid(s);
out("root", { id, sessionId: s.sessionId, workerPid: s.workerPid });
await C.attach(c1, id);
const tag = `SLOW:30:500`; const mockBefore = C.mockRequests().length;
out("prompt (15s of streaming)", await C.prompt(c1, id, tag));
await c1.waitFor((e) => e.event?.type === "message_update", 20000);
const cursor = c1.lastCursor; out("cursor at detach", cursor);
c1.close(); out("client socket destroyed abruptly at", new Date().toISOString());
await C.sleep(20000);
const reqs = C.mockRequests().slice(mockBefore).filter((r) => r.lastUser === tag);
const done = C.mockEntries((e) => e.kind === "response" && e.mode === "slow" && e.id === reqs[0]?.id);
const gone = C.mockEntries((e) => e.kind === "client-gone" && e.id === reqs[0]?.id);
out("mock: requests for this prompt", reqs.length, "completed responses", done.length, "client-gone", gone.length);
out.check("worker kept consuming the model stream after client detach (no client-gone, 1 request, completed)", reqs.length === 1 && done.length === 1 && gone.length === 0);
const listed = (await C.list(await C.newClient("cg-detach-l", out))).find((x) => C.sid(x) === id);
out("list after detach", { state: listed?.workerState, activity: listed?.activity, clients: listed?.attachedClients, pid: listed?.workerPid });
out.check("worker survived with zero attached clients", listed?.attachedClients === 0 && listed?.workerPid === s.workerPid && listed?.workerState === "ready");
const c2 = await C.newClient("cg-detach-2", out);
const a = await C.attach(c2, id, { resumeCursor: cursor });
out("reattach", a.success ? { replay: a.data.replay, lastEventCursor: a.data.lastEventCursor, activeSessionId: a.data.activeSessionId, sessionId: a.data.snapshot?.summary?.sessionId ?? a.data.state?.sessionId } : a);
const st = await C.getState(c2, id); const m = await C.getMessages(c2, id);
const text = JSON.stringify((m.data.messages ?? m.data).at(-1)?.content ?? "");
out("last message", text.slice(0, 120));
out.check("reattached to the exact same session identity", a.success && a.data.activeSessionId === id && st.data.sessionId === s.sessionId);
out.check("completed assistant turn visible after reattach (tick29 present, not streaming)", text.includes("tick29") && st.data.isStreaming === false);
out.check("replay info returned for the presented cursor", !!a.data?.replay?.status, a.data?.replay);
c2.close(); process.exit(out.failed ? 1 : 0);
