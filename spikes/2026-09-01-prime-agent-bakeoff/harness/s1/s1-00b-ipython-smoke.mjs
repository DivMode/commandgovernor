import fs from "node:fs";
import * as C from "./common.mjs";
const RUN = Date.now().toString(36);
const out = C.evidence("s1-00b-ipython-smoke");
const c = await C.newClient("cg-ipy", out);
const s = await C.createRoot(c, { name: `cg-s1-00b-${RUN}` });
const id = C.sid(s); out("root", { id, workerPid: s.workerPid });
await C.attach(c, id);
const target = `${C.WORK}/ipy-smoke-${Date.now()}.txt`;
const code = `open(${JSON.stringify(target)}, "w").write("hi from kernel")`;
const before = C.mockRequests().length;
const t0 = Date.now();
out("prompt", await C.prompt(c, id, `TOOL:ipython:${JSON.stringify({ code })}`));
out("idle", (await C.waitForIdle(c, id, 300000)).success ? `ok after ${Date.now() - t0}ms` : "FAILED");
const m = await C.getMessages(c, id);
out("messages", (m.data.messages ?? m.data).map((x) => ({ role: x.role, text: JSON.stringify(x.content).slice(0, 160) })));
out("mock requests during", C.mockRequests().slice(before).map((r) => ({ lastRole: r.lastRole, lastUser: r.lastUser?.slice(0, 40), tools: r.toolNames })));
out.check("kernel executed the tool call and wrote the file", fs.existsSync(target) && fs.readFileSync(target, "utf8") === "hi from kernel");
out.check("events carry generation cursors", !!c.lastCursor?.generation, c.lastCursor);
out("event types", [...new Set(c.events.map((e) => e.event?.type ?? e.type))]);
c.close(); process.exit(out.failed ? 1 : 0);
