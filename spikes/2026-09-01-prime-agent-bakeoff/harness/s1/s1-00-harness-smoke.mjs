import * as C from "./common.mjs";
const RUN = Date.now().toString(36);
const out = C.evidence("s1-00-harness-smoke");
const c = await C.newClient("cg-smoke", out);
out("hello", { protocol: c.hello.protocol, schemaRevision: c.hello.schemaRevision, appVersion: c.hello.appVersion, supervisorPid: c.hello.supervisorPid, supervisorGeneration: c.hello.supervisorGeneration, caps: c.hello.serverCapabilities });
out("list before", (await C.list(c)).map((s) => ({ id: C.sid(s), state: s.workerState, pid: s.workerPid, clients: s.attachedClients, activity: s.activity })));
const s = await C.createRoot(c, { name: `cg-smoke-root-${RUN}` });
out("created", { id: C.sid(s), sessionId: s.sessionId, file: s.sessionFile, workerPid: s.workerPid, workerState: s.workerState, model: s.model?.id });
const a = await C.attach(c, C.sid(s));
out("attach", a.success ? { replay: a.data.replay, lastEventCursor: a.data.lastEventCursor, snapshotMessages: a.data.snapshot?.messages?.length ?? a.data.messages?.length, client: a.data.client } : a);
const p = await C.prompt(c, C.sid(s), "ECHO:smoke-hello");
out("prompt response", p);
const idle = await C.waitForIdle(c, C.sid(s));
out("wait_for_idle", idle.success ? "ok" : idle);
const st = await C.getState(c, C.sid(s));
out("state", st.success ? { isStreaming: st.data.isStreaming, messageCount: st.data.messageCount, activeSessionId: st.data.activeSessionId } : st);
const m = await C.getMessages(c, C.sid(s));
out("messages", m.success ? (m.data.messages ?? m.data).map((x) => ({ role: x.role, text: JSON.stringify(x.content).slice(0, 80) })) : m);
out("events seen", c.events.map((e) => `${e.event?.type}@${e.cursor?.generation?.slice(0, 8)}:${e.cursor?.sequence}`).slice(0, 40));
out("lastCursor", c.lastCursor);
out.check("echo answered by mock", JSON.stringify(m.data).includes("smoke-hello"));
out.check("events carry generation cursors", !!c.lastCursor?.generation && Number.isInteger(c.lastCursor?.sequence));
c.close();
process.exit(out.failed ? 1 : 0);
